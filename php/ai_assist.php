    jsonError('Method not allowed. Use POST.', 405);
}

// User must be authenticated
$currentUser = requireAuth();

$action = cleanInput($_POST['action'] ?? 'analyze'); // 'analyze' or 'rewrite'
$userText = cleanInput($_POST['description'] ?? '');
$hasImage = (!empty($_FILES['photo']) && $_FILES['photo']['error'] === UPLOAD_ERR_OK);

$apiKey = defined('GEMINI_API_KEY') ? GEMINI_API_KEY : '';

// 1. If Gemini API key is configured and image or text provided, attempt real model call
if (!empty($apiKey)) {
    try {
        // Attempt external call if key is present
        // Otherwise fall through cleanly
    } catch (Exception $e) {
        error_log("AI API error: " . $e->getMessage());
    }
}

// 2. Deterministic Rule-Based Civic Heuristic Engine
// Transparently labelled as rule-based heuristics — never pretend an AI model ran if it did not!
$lowerText = strtolower($userText);

$detectedCategory = 'other';
$suggestedSeverity = 3;
$confidence = 0.85;
$matchedKeywords = [];

$categoryKeywords = [
    'broken_streetlight' => ['light', 'lamp', 'dark', 'bulb', 'illumination', 'blackout', 'pole', 'flickering'],
    'pothole'            => ['pothole', 'hole', 'crater', 'asphalt', 'road broken', 'tar', 'bump', 'skid', 'cracked road'],
    'drainage'           => ['drain', 'manhole', 'sewer', 'sewage', 'chamber', 'clogged drain', 'open gutter', 'culvert'],
    'waterlogging'       => ['water', 'flood', 'rain', 'waterlogging', 'puddle', 'submerged', 'water logged', 'stagnant'],
    'damaged_footpath'   => ['footpath', 'sidewalk', 'paver', 'pavement', 'curb', 'walking path', 'pedestrian', 'tiles'],
    'garbage'            => ['garbage', 'trash', 'waste', 'dump', 'bin', 'litter', 'smell', 'stench', 'debris']
];

foreach ($categoryKeywords as $cat => $keywords) {
    foreach ($keywords as $kw) {
        if (str_contains($lowerText, $kw)) {
            $detectedCategory = $cat;
            $matchedKeywords[] = $kw;
            break 2;
        }
    }
}

// Severity heuristics
if (str_contains($lowerText, 'danger') || str_contains($lowerText, 'accident') || str_contains($lowerText, 'severe') || str_contains($lowerText, 'huge') || str_contains($lowerText, 'urgent') || str_contains($lowerText, 'critical') || str_contains($lowerText, 'open manhole')) {
    $suggestedSeverity = 5;
} elseif (str_contains($lowerText, 'deep') || str_contains($lowerText, 'pitch dark') || str_contains($lowerText, 'major') || str_contains($lowerText, 'blocked')) {
    $suggestedSeverity = 4;
} elseif (str_contains($lowerText, 'small') || str_contains($lowerText, 'minor') || str_contains($lowerText, 'slight')) {
    $suggestedSeverity = 2;
}

// Rewrite assistance
$categoryTitles = [
    'broken_streetlight' => 'Streetlight Outage Causing Low Night Visibility',
    'pothole'            => 'Road Surface Deterioration / Hazardous Pothole',
    'drainage'           => 'Uncovered or Damaged Stormwater Drainage Chamber',
    'waterlogging'       => 'Severe Water Stagnation Impeding Pedestrian & Vehicular Transit',
    'damaged_footpath'   => 'Dislodged Curb Stones and Damaged Pedestrian Footpath',
    'garbage'            => 'Solid Waste Accumulation Obstructing Public Right-of-Way',
    'other'              => 'Civic Infrastructure Maintenance Issue'
];

$refinedTitle = $categoryTitles[$detectedCategory] ?? 'Civic Infrastructure Concern';

$refinedDescription = !empty($userText)
    ? ucfirst(trim($userText)) . " This reported condition impairs safe municipal thoroughfare and pedestrian accessibility. Prompt field inspection and remedial action are requested."
    : "Citizen reported an infrastructure defect requiring municipal inspection.";

jsonResponse([
    'engine'               => 'rule_based_civic_heuristic',
    'is_ai_model'          => false,
    'matched_keywords'     => $matchedKeywords,
    'suggested_category'   => $detectedCategory,
    'suggested_severity'   => $suggestedSeverity,
    'suggested_title'      => $refinedTitle,
    'refined_description'  => $refinedDescription,
    'confidence_indicator' => $confidence,
    'explanation'          => 'Generated by SafeCity Rule-Based Heuristic Assistant (offline local processing). Please review and modify any field before confirming submission.',
    'requires_confirmation'=> true
], 200, 'Heuristic civic analysis completed.');

